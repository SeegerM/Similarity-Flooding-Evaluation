"""Write output/src_numbers.tex: the source-sensitivity review check (EXPLORATORY, 2026-10-29), macros prefixed src.

Source: results/sf_study/tuning/results/review_checks/source_sensitivity.json, written by
experiments/sf_study/review_checks/source_sensitivity.py from cached scores only (report: source_sensitivity.md next to it).
Numbers are parsed, never typed.

  B1  RQ1 panel (layer 1, SF as published, readable Valentine) without the SemStruct reimplementation:
      srcNoSs...      without `semstruct` (the only SemStruct-derived member);
      srcNoSsEfive... also without `sbert_e5` (same frozen encoder as SemStruct's LM-only control; stricter variant).
      Suffixes as in rq1_numbers.tex (rqOne...) and review_numbers.tex (rv...).
  B2  Leave one source out (LOSO) on readable Valentine (10 source tables, X77's source_id):
      Gain = SF as published - initial matcher (RQ1 panel), Dt = datatype term q+ + 5D - SF as published (X46 panel,
      the info-ladder row), Rho = Spearman over matchers of quality and SF's change. Loso...Min/Max: range of the macro
      estimate with one source dropped; ...Flips: drops whose estimate has the opposite sign of the full estimate;
      Src...: per-source estimates (plain mean over the source's scenarios); ...Opp: sources of the opposite sign.

    python make_src_numbers.py
"""

from __future__ import annotations

import json

from paths import STUDY
from paths import OUT as OUT_DIR
SRC = STUDY / "tuning" / "results" / "review_checks" / "source_sensitivity.json"
OUT = OUT_DIR / "src_numbers.tex"


def f3(v: float) -> str:
    return f"{v:+.3f}"


def fr(v: float) -> str:          # rho, formatted as make_study_numbers.rq_numbers does
    return f"{v:.2f}"


def src_name(s: str) -> str:
    """'TPC/prospect' -> 'TPC-DI'; single-source families by family name, Magellan tables as 'Magellan (dblp)'."""
    fam, table = s.split("/", 1)
    return {"TPC": "TPC-DI", "ChEMBL": "ChEMBL", "OpenData": "OpenData", "Wikidata": "Wikidata"}.get(
        fam, f"{fam} ({table})")


def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    b1, b2 = d["b1"], d["b2"]
    m: dict[str, str] = {}
    # ---- B1
    for var, pre in (("noss", "NoSs"), ("noss_e5", "NoSsEfive")):
        v = b1[var]
        m[f"{pre}N"] = str(v["n"])
        m[f"{pre}Dropped"] = str(len(v["dropped"]))
        for k in ("UpRexp", "UpFHr", "MeanRexp", "MeanFHr", "RhoRexp", "RhoFHr", "RhoFamRexp", "RhoFamFHr", "NFam"):
            m[f"{pre}{k}"] = v["rq"][k]
        for k in ("SplitRexp", "SplitRexpLo", "SplitRexpHi", "SplitFHr", "SplitFHrLo", "SplitFHrHi",
                  "NullRexp", "NullRexpLo", "NullRexpHi", "NullFHr", "NullFHrLo", "NullFHrHi",
                  "HeadRexp", "HeadFHr", "RelNullRexp", "RelNullRexpLo", "RelNullRexpHi", "RelNullPRexp",
                  "RelNullFHr", "RelNullFHrLo", "RelNullFHrHi", "RelNullPFHr"):
            m[f"{pre}{k}"] = v["rv"][k]
    # ---- B2
    src = b2["sources"]
    m["NSources"] = str(len(src))
    m["NScen"] = str(sum(i["n"] for i in src.values()))
    big = [s for s, i in src.items() if i["n"] >= 5]
    m["NSourcesBig"] = str(len(big))
    m["NScenBig"] = str(sum(src[s]["n"] for s in big))
    m["NMagellanSources"] = str(sum(1 for s in src if s.startswith("Magellan/")))
    m["NPanelGain"] = str(b2["n_panel_gain"])
    m["NPanelDt"] = str(b2["n_panel_dt"])
    S = b2["summary"]
    keys = {"Gain": ("d_J", f3), "GainRexp": ("d_R_exp", f3), "GainFHr": ("d_F1_Hr", f3),
            "RhoRexp": ("rho_R_exp", fr), "RhoFHr": ("rho_F1_Hr", fr),
            "Dt": ("dt_J", f3), "DtRexp": ("dt_R_exp", f3), "DtFHr": ("dt_F1_Hr", f3), "DtNoSs": ("dt_noss_J", f3)}
    for name, (k, fmt) in keys.items():
        x = S[k]
        m[f"Full{name}"] = fmt(x["full"])
        m[f"Loso{name}Min"], m[f"Loso{name}Max"] = fmt(x["min"]), fmt(x["max"])
        m[f"Loso{name}MinSrc"], m[f"Loso{name}MaxSrc"] = src_name(x["argmin"]), src_name(x["argmax"])
        m[f"Loso{name}Flips"] = str(x["flips"])
        m[f"Loso{name}NearZero"] = str(x["near_zero"])
        if "src_min" in x:
            m[f"Src{name}Min"], m[f"Src{name}Max"] = fmt(x["src_min"]), fmt(x["src_max"])
            m[f"Src{name}Opp"] = str(x["src_opposite"])
    # per-source estimates of the three large sources (each one Valentine family)
    for s in big:
        tag = {"TPC": "Tpc", "ChEMBL": "Chembl", "OpenData": "Opendata"}[s.split("/")[0]]
        e = d["b2"]["per_source"][s]
        m[f"Src{tag}N"] = str(src[s]["n"])
        m[f"Src{tag}Gain"], m[f"Src{tag}Dt"] = f3(e["d_J"]), f3(e["dt_J"])
        m[f"Src{tag}GainRexp"], m[f"Src{tag}GainFHr"] = f3(e["d_R_exp"]), f3(e["d_F1_Hr"])
        m[f"Src{tag}RhoRexp"], m[f"Src{tag}RhoFHr"] = fr(e["rho_R_exp"]), fr(e["rho_F1_Hr"])
    head = ("% Generated by make_src_numbers.py from results/sf_study/tuning/results/review_checks/source_sensitivity.json\n"
            "% (review_checks/source_sensitivity.py; cached scores only); EXPLORATORY; do not edit.\n"
            "% NoSs: RQ1 panel without semstruct; NoSsEfive: also without sbert_e5. Loso: leave one Valentine source out.\n")
    OUT.write_text(head + "".join(f"\\newcommand{{\\src{k}}}{{{v}}}\n" for k, v in m.items()), encoding="utf-8")
    print(f"wrote {OUT} ({len(m)} macros)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

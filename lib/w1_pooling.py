def _madi_J():
    """Unrounded J_tf intervals of the MaDI datatype and class cells (recall_cells.csv; review 7, W3)."""
    out = {}
    for x in csv.DictReader(open(DERIVED / 'recall' / 'recall_cells.csv', encoding='utf8')):
        if x['corpus'].startswith('MaDI') and x['col'] in ('dt', 'cl') and x.get('J_lo') not in ('', 'nan', None):
            out[(x['corpus'], x['col'])] = (float(x['J']), float(x['J_lo']), float(x['J_hi']))
    return out


def cells(metric, with_ci_only, umap=None, drop=()):
    """[(corpus, unit, group, col, e, se or None)] of information-matched term cells."""
    rows = ROWS_R if metric == 'R' else ROWS
    reg = registered_role_J()
    mj = _madi_J() if metric == 'J' else {}
    um = dict(UNIT, **(umap or {}))
    out = []
    for label, g, cc in rows:
        if label in drop:
            continue
        for k in TERM_COLS:
            c = cc[k]
            if c == NI_R and metric == 'J' and label in reg:
                c = reg[label]
            if not isinstance(c, dict) or c['nm']:
                continue
            if (label, k) in mj and c['l'] is None:
                e, lo, hi = mj[(label, k)]
                c = dict(c, l=lo, h=hi)
            has = c['l'] is not None
            if with_ci_only and not has:
                continue
            se = (c['h'] - c['l']) / (2 * 1.959964) if has else None
            out.append((label, um.get(label, label), g, k, c['e'], se, c['l'], c['h']))
    return out


def unit_table(cs):
    """{(unit, col): (e, se or None)} with variants averaged; {unit: group}."""
    by, grp = {}, {}
    for _, u, g, k, e, se, _, _ in cs:
        by.setdefault((u, k), []).append((e, se))
        grp[u] = g
    ut = {}
    for key, v in by.items():
        ses = [s for _, s in v if s is not None]
        ut[key] = (float(np.mean([e for e, _ in v])), float(np.mean(ses)) if len(ses) == len(v) else None)
    return ut, grp


def unit_scores(ut, grp, adjust):
    colmean = {k: np.mean([e for (u, kk), (e, _) in ut.items() if kk == k]) for k in TERM_COLS
               if any(kk == k for (_, kk) in ut)}
    sc = {}
    for u in grp:
        v = [e - (colmean[k] if adjust else 0.0) for (uu, k), (e, _) in ut.items() if uu == u]
        sc[u] = float(np.mean(v))
    return sc


def perm_test(sc, grp):
    units = sorted(sc)
    x = np.array([sc[u] for u in units])
    g = np.array([grp[u] for u in units])
    n0 = int((g == 0).sum())
    obs = x[g == 0].mean() - x[g == 1].mean()
    ds = []
    for idx in itertools.combinations(range(len(units)), n0):
        m = np.zeros(len(units), bool)
        m[list(idx)] = True
        ds.append(x[m].mean() - x[~m].mean())
    ds = np.array(ds)
    p = float(np.mean(np.abs(ds) >= abs(obs) - 1e-12))
    loo = []
    for i, u in enumerate(units):
        keep = np.arange(len(units)) != i
        xx, gg = x[keep], g[keep]
        if (gg == 0).any() and (gg == 1).any():
            loo.append((xx[gg == 0].mean() - xx[gg == 1].mean(), u))
    return obs, p, len(ds), x[g == 0].mean(), x[g == 1].mean(), min(loo), max(loo)


def re_pool(es, ses):
    """DerSimonian-Laird random-effects mean with Hartung-Knapp 95% interval; (mean, lo, hi, tau, k)."""
    es, ses = np.asarray(es), np.asarray(ses)
    k = len(es)
    if k == 0:
        return None
    if k == 1:
        return es[0], es[0] - 1.96 * ses[0], es[0] + 1.96 * ses[0], 0.0, 1
    w = 1 / ses ** 2
    fe = np.sum(w * es) / np.sum(w)
    q = np.sum(w * (es - fe) ** 2)
    c = np.sum(w) - np.sum(w ** 2) / np.sum(w)
    tau2 = max(0.0, (q - (k - 1)) / c)
    ws = 1 / (ses ** 2 + tau2)
    mu = np.sum(ws * es) / np.sum(ws)
    var_hk = np.sum(ws * (es - mu) ** 2) / ((k - 1) * np.sum(ws))
    t = stats.t.ppf(0.975, k - 1)
    return mu, mu - t * math.sqrt(var_hk), mu + t * math.sqrt(var_hk), math.sqrt(tau2), k


def per_column(ut, grp):
    res = {}
    for k in TERM_COLS:
        sub = {u: e for (u, kk), (e, _) in ut.items() if kk == k}
        pools = {}
        for g in (0, 1):
            v = [(ut[(u, k)][0], ut[(u, k)][1]) for u in sub if grp[u] == g and ut[(u, k)][1] is not None]
            pools[g] = re_pool([a for a, _ in v], [b for _, b in v]) if v else None
        p = None
        if sum(grp[u] == 0 for u in sub) and sum(grp[u] == 1 for u in sub):
            p = perm_test(sub, {u: grp[u] for u in sub})
        res[k] = (pools, p, sub)
    return res


def recount(cs):
    out = {}
    for g in (0, 1):
        term = sf = tie = unclear = 0
        for _, _, gg, _, e, se, l, h in cs:
            if gg != g or l is None:
                continue
            if abs(e) < MARGIN:
                tie += 1
            elif l > 0:
                term += 1
            elif h < 0:
                sf += 1
            else:
                unclear += 1
        out[g] = (term, sf, tie, unclear)
    return out


def f(x):
    return '%+.3f' % x



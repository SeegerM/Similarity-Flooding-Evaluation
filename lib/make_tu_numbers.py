"""Write output/tu_numbers.tex: the two-update closed form's direct-literal offset (review check, 2026-10-29).
Source, parsed, nothing typed: results/sf_study/tuning/results/review_checks/two_update_offset.csv
(review_checks/two_update_offset_check.py over the cached SF graph exports).

    python make_tu_numbers.py
"""

from __future__ import annotations

import csv

from paths import OUT, STUDY
SRC = STUDY / "tuning" / "results" / "review_checks" / "two_update_offset.csv"
rows = list(csv.DictReader(SRC.open(encoding="utf-8")))
single = [r for r in rows if r["single_table"] == "1"]
nonconstant = [r for r in rows if float(r["B_spread"]) > 1e-9]
out = {"tuN": str(len(rows)), "tuSingleN": str(len(single)), "tuNonConst": str(len(nonconstant))}
lines = ["% Generated by make_tu_numbers.py from results/sf_study/tuning/results/review_checks/two_update_offset.csv "
         "(two_update_offset_check.py); do not edit."]
lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in out.items()]
(OUT / "tu_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))

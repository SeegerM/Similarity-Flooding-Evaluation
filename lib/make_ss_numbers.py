"""Write output/ss_numbers.tex: the SemStruct information-matched ablation (the SemStruct ablation plan, Amendment 1,
EXPLORATORY) on readable Valentine, cohort remaining505 (the 337 remaining scenarios of the earlier copy + the 168 new;
Amendment 2b). Source: the evaluation report written by experiments/baselines/semstruct_ablation_eval.py
(reports/semstruct_ablation_549/eval_plain/report.md), parsed, nothing typed. GOBY was not rerun: its macros read the
earlier run (reports/semstruct_ablation_20261027/goby/).

    python make_ss_numbers.py
"""

from __future__ import annotations

import re

from paths import BASELINES, OUT
COHORT = "remaining505"
A382 = BASELINES / "reports" / "semstruct_ablation_20261027"
A = BASELINES / "reports" / "semstruct_ablation_549"
REPORT = A / "eval_plain" / "report.md"
text = REPORT.read_text(encoding="utf-8")
block = text[text.index(f"## {COHORT}"):text.index("## all")]
n = int(re.search(rf"## {COHORT}: (\d+) scenarios", block).group(1))


def contrast(a: str, b: str) -> tuple[str, str, str]:
    row = next(l for l in block.splitlines() if l.startswith(f"| {a} − {b} |"))
    est, lo, hi = re.findall(r"[+-]\d+\.\d+", row.split("|")[3])
    return est, lo, hi


def arm(name: str) -> str:
    row = next(l for l in block.splitlines() if l.startswith(f"| {name} |"))
    return row.split("|")[2].strip()


out = {"ssN": str(n)}
out["ssGate"], out["ssGateLo"], out["ssGateHi"] = contrast("full", "lm_only")
out["ssOneFull"], out["ssOneFullLo"], out["ssOneFullHi"] = contrast("onehop", "full")
out["ssFullPerm"], _, _ = contrast("full", "full_permuted")
out["ssJFull"], out["ssJOne"], out["ssJLm"] = arm("full"), arm("onehop"), arm("lm_only")
assert "zero_delta reproduces lm_only, max |ΔJ| = 0.00e+00" in text, "zero_delta control failed"
# GOBY (trained on its own source tables; clustered bootstrap): report written by the same evaluation script
GOBY = A382 / "goby" / "eval_plain_goby-imported" / "report.md"
gtext = GOBY.read_text(encoding="utf-8")
gblock = gtext[gtext.index("## all"):]
assert "zero_delta reproduces lm_only, max |ΔJ| = 0.00e+00" in gtext


def gcontrast(a: str, b: str) -> tuple[str, str, str]:
    row = next(l for l in gblock.splitlines() if l.startswith(f"| {a} − {b} |"))
    est, lo, hi = re.findall(r"[+-]\d+\.\d+", row.split("|")[3])
    return est, lo, hi


out["ssGobyN"] = re.search(r"## all: (\d+) scenarios", gblock).group(1)
out["ssGobyClusters"] = re.search(r"(\d+) clusters of scenarios", gtext).group(1)
out["ssGobyGate"], out["ssGobyGateLo"], out["ssGobyGateHi"] = gcontrast("full", "lm_only")
out["ssGobyOneFull"], out["ssGobyOneFullLo"], out["ssGobyOneFullHi"] = gcontrast("onehop", "full")
# no-merging sensitivity (the paper's A.4 tau = 0), specified before running; same script, arms suffixed __merge-none
NM = A / "nomerge" / "eval_plain" / "report.md"
ntext = NM.read_text(encoding="utf-8")
nblock = ntext[ntext.index(f"## {COHORT}"):ntext.index("## all")]
assert "zero_delta reproduces lm_only, max |ΔJ| = 0.00e+00" in ntext


def ncontrast(a: str, b: str) -> tuple[str, str, str]:
    row = next(l for l in nblock.splitlines() if l.startswith(f"| {a} − {b} |"))
    est, lo, hi = re.findall(r"[+-]\d+\.\d+", row.split("|")[3])
    return est, lo, hi


out["ssNmGate"], out["ssNmGateLo"], out["ssNmGateHi"] = ncontrast("full", "lm_only")
out["ssNmOneFull"], out["ssNmOneFullLo"], out["ssNmOneFullHi"] = ncontrast("onehop", "full")
out["ssNmFullPerm"], _, _ = ncontrast("full", "full_permuted")
lines = [f"% Generated by make_ss_numbers.py from results/baselines/reports/{A.name}/eval_plain/report.md "
         f"(semstruct_ablation_eval.py; SEMSTRUCT_ABLATION.md, Amendment 1 on 549 (Amendment 2b); GOBY from {A382.name}); "
         "EXPLORATORY; do not edit."]
lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in out.items()]
(OUT / "ss_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))

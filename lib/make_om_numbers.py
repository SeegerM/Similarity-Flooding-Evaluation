"""Write output/om_numbers.tex: the OmniMatch information-matched ablation (the OmniMatch ablation plan, EXPLORATORY).
Sources, parsed, nothing typed:
- results/baselines/reports/omnimatch_ablation_549/report_valentine_plain.md (our port of the authors' release, readable
  Valentine, cohort remaining505 = the 337 remaining of the earlier copy + the 168 new scenarios, seeds 1-3 averaged
  per scenario; omnimatch_ablation.py report, the ablation plan's Amendment 549);
- results/baselines/reports/omnimatch_release_549/report.md (the authors' release itself, the validation).

    python make_om_numbers.py
"""

from __future__ import annotations

import csv
import re

from paths import BASELINES, OUT
H = BASELINES / "reports"
COHORT = "remaining505"   # the 549 without the 44 inspected scenarios
PORT, REL = "omnimatch_ablation_549", "omnimatch_release_549"
text = (H / PORT / "report_valentine_plain.md").read_text(encoding="utf-8")
block = text[text.index(f"## {COHORT}"):text.index("## all")]
n = int(re.search(rf"## {COHORT}: (\d+) scenarios", block).group(1))


def contrast(a: str, b: str) -> tuple[str, str, str]:
    row = next(l for l in block.splitlines() if l.startswith(f"| {a} - {b} |"))
    est, lo, hi = re.findall(r"[+-]\d+\.\d+", row.split("|")[3])
    return est, lo, hi


def arm(name: str) -> str:
    row = next(l for l in block.splitlines() if l.startswith(f"| {name} |"))
    return row.split("|")[2].strip()


out = {"omN": str(n)}
out["omEdge"], out["omEdgeLo"], out["omEdgeHi"] = contrast("F", "N")
rf = contrast("RF", "F")
out["omRfF"], out["omRfFLo"], out["omRfFHi"] = rf
out["omJF"], out["omJN"], out["omJRf"] = arm("F"), arm("N"), arm("RF")
rel = (H / REL / "report.md").read_text(encoding="utf-8")
m = re.search(r"\| release rgcn − release no-edge \| ([+-−]\d+\.\d+) \[([+-−]\d+\.\d+), ([+-−]\d+\.\d+)\]", rel)
out["omRelEdge"], out["omRelEdgeLo"], out["omRelEdgeHi"] = (x.replace("−", "-") for x in m.groups())
out["omRelN"] = re.search(r"The (\d+) step-0 scenarios", rel).group(1)
m = re.search(r"\| release rgcn − port F \| ([+-−]\d+\.\d+)", rel)
out["omRelPort"] = m.group(1).replace("−", "-")
# per scenario (per_scenario_J.csv, seeds averaged): how often the release's edges lose, and how far release and port
# differ on single scenarios
with open(H / REL / "per_scenario_J.csv", encoding="utf-8") as f:
    rows = list(csv.DictReader(f))
out["omRelEdgeNeg"] = str(sum(float(r["release:rgcn_margin"]) < float(r["release:rgcn_margin_noedges"]) for r in rows))
out["omRelPortMax"] = f"{max(abs(float(r['release:rgcn_margin']) - float(r['port:F'])) for r in rows):.2f}"
lines =[f"% Generated by make_om_numbers.py from results/baselines/reports/{PORT}/report_valentine_plain.md and "
         f"{REL}/report.md (OMNIMATCH_ABLATION.md, Amendment 549); EXPLORATORY; do not edit."]
lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in out.items()]
(OUT / "om_numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))

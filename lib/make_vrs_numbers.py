"""Write output/vrs_numbers.tex: the Valentine base of the paper (macros prefixed vrs).

Numbers are parsed, never typed:
  results/baselines/valentine549/cohort-549.json        the official Valentine release and the 549 cohort
      (total_release, valid, excluded, prior_protocol_cases, prior_distinct_scenarios, new_cohort), written by
      experiments/baselines/valentine549/freeze_cohort.py;
  results/sf_study/results/valentine549/assembly.json   the assembly's per-matcher flags (assemble_549.py); the ISResMat
      flag states how far two runs of its (unseeded) GPU training differ per cell;
  results/baselines/generated_hyfdfix/gdcsm/*/metadata/profiling.json   GDC-SM's fixed FD profiles (FDs of its target);
  results/sf_study/results/x81fix/report.md             GDC-SM on the fixed profiles (mean J_tf per SF arm);
  results/baselines/reports/semstruct_a2_549/a2_*V41*/checkpoints/a2.json   SemStruct's training and validation tables.
Checks: valid = prior distinct + new; valid + excluded = release; the assembled case list has the cohort's scenarios;
every ISResMat flag names the same bound; the target FD count is the same in all GDC-SM scenarios; every readable
SemStruct checkpoint trains on the same tables.

    python make_vrs_numbers.py
"""

from __future__ import annotations

import json
import re

from paths import BASELINES, OUT, STUDY
COHORT = BASELINES / "valentine549" / "cohort-549.json"
ASSEMBLY = STUDY / "results" / "valentine549" / "assembly.json"
GDC = BASELINES / "generated_hyfdfix" / "gdcsm" / "GDCSM-Unionable"
X81FIX = STUDY / "results" / "x81fix" / "report.md"
SS = BASELINES / "reports" / "semstruct_a2_549"


def flags(node, out: list) -> list:
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "flags" and isinstance(v, dict):
                out += [s for m, s in v.items() if m in ("isresmat", "isresmat_hybrid")]
            else:
                flags(v, out)
    elif isinstance(node, list):
        for v in node:
            flags(v, out)
    return out


def main() -> int:
    c = json.loads(COHORT.read_text(encoding="utf-8"))
    valid, release, excl = int(c["valid"]), int(c["total_release"]), len(c["excluded"])
    prior, distinct, new = int(c["prior_protocol_cases"]), int(c["prior_distinct_scenarios"]), int(c["new_cohort"])
    assert valid == distinct + new and valid + excl == release, (valid, distinct, new, excl, release)
    assert len(c["prior_cases"]) == distinct and len(c["new_cases"]) == new
    # independent check: the assembled case list has exactly the cohort's scenarios, old and new
    cases = [ln.split(",") for ln in (STUDY / "results" / "valentine549" / "cases.csv").read_text(encoding="utf-8")
             .splitlines()[1:]]
    assert len(cases) == valid and sum(x[3] == "old381" for x in cases) == distinct, (len(cases), valid)
    fl = flags(json.loads(ASSEMBLY.read_text(encoding="utf-8")), [])
    bounds = {re.search(r"differ by up to ([0-9.]+) per cell", s).group(1) for s in fl}
    assert fl and len(bounds) == 1, bounds
    m = {"NRelease": str(release), "NValid": str(valid), "NExcluded": str(excl), "NPriorCases": str(prior),
         "NPriorDistinct": str(distinct), "NNew": str(new), "IsrCellDiff": bounds.pop()}
    # GDC-SM on the fixed FD profiles: the FDs of its shared target (as the graph builder reads them:
    # profiling.json target.fd.compatibility_count, identical in all scenarios) and the mean J_tf of SF as published,
    # with all FD edges and with the key plus top-k FD edges (results/x81fix/report.md, section gdcsm)
    counts = {json.loads((d / "metadata" / "profiling.json").read_text(encoding="utf-8"))["target"]["fd"]["compatibility_count"]
              for d in sorted(GDC.iterdir()) if d.is_dir()}
    assert len(counts) == 1, counts
    m["GdcTargetFds"] = f"{counts.pop():,}".replace(",", "{,}")
    sec = X81FIX.read_text(encoding="utf-8").split("\n## gdcsm\n", 1)[1].split("\n## ", 1)[0]
    ref = float(re.search(r"mean J_tf: .*\bmelnik ([0-9.]+)", sec).group(1))
    fd = re.search(r"mean J_tf, FD arms: fd ([0-9.]+), ucc1_fd_topk ([0-9.]+)", sec)
    m["GdcRefJ"], m["GdcFdJ"], m["GdcTopkJ"] = f"{ref:.3f}", f"{float(fd.group(1)):.3f}", f"{float(fd.group(2)):.3f}"
    assert "E4 R_exp SF(fd) − SF(melnik)" in sec
    # SemStruct (Amendment 2b): distinct Valentine source tables its models train on (training + validation), equal in
    # every readable Valentine checkpoint
    tabs = {(c["n_training_tables"], c["n_validation_tables"])
            for c in (json.loads(p.read_text(encoding="utf-8")) for p in SS.glob("a2_*V41*/checkpoints/a2.json"))}
    assert len(tabs) == 1, tabs
    m["SsTables"] = str(sum(tabs.pop()))
    head = ("% Generated by make_vrs_numbers.py from results/baselines/valentine549/cohort-549.json and\n"
            "% results/sf_study/results/valentine549/assembly.json (ISResMat flag); Gdc*: results/baselines/generated_hyfdfix/gdcsm\n"
            "% profiles and results/sf_study/results/x81fix/report.md; do not edit.\n"
            "% Release: official Valentine scenarios; Valid: the 549 base; PriorCases / PriorDistinct: the earlier copy.\n")
    (OUT / "vrs_numbers.tex").write_text(head + "".join(f"\\newcommand{{\\vrs{k}}}{{{v}}}\n" for k, v in m.items()),
                                         encoding="utf-8")
    print(f"wrote {OUT / 'vrs_numbers.tex'} ({len(m)} macros): {m}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
